export type RhythmKind = 'run' | 'sync' | 'dotted' | 'long' | 'sparse' | 'swingline';
export type BassKind = 'root' | 'octave' | 'walk' | 'sync' | 'pedal' | 'arpbass' | 'sustained' | 'fifth' | 'oompah' | 'pop' | 'kbass' | 'rnb' | 'house' | 'rock8' | 'bossa' | 'disco' | 'reggae' | 'trap808' | 'tumbao';
export type CompKind = 'none' | 'stabs' | 'charleston' | 'skank' | 'block' | 'strum' | 'oompah' | 'pianoPop' | 'pianoBallad' | 'strumGuitar' | 'offbeat' | 'rnbKeys' | 'powerChug' | 'bossaGtr' | 'alberti' | 'dembow' | 'discoGtr';
/** 「記得住的旋律」使用的節奏家族 */
export type HookFamily = 'pop' | 'kpop' | 'rnb' | 'ballad' | 'rock' | 'dance' | 'latin' | 'bossa' | 'swing' | 'classic';
export type ArpKind = 'up' | 'updown' | 'broken' | 'bounce';

export interface GenreSpec {
  id: GenreId;
  name: string;
  desc: string;
  bpm: [number, number];
  meter?: 3 | 4;
  modes: Mode[];
  keys: number[];
  /** 和弦進行（音階級數，0 起算），會循環套到每個小節 */
  progs: number[][];
  chordsPerBar?: 1 | 2;
  chordKind: ChordKind;
  swing: number;
  drums: string;
  bass: BassKind;
  comp: CompKind;
  /** family：使用動機式旋律（A–A'–A–B 的樂句，重複與變化），沒有就用舊的隨機旋律 */
  lead?: { rhythm: RhythmKind; family?: HookFamily; density: number; range: [number, number]; legato: number };
  /** 鼓組風格：acoustic 全取樣、hybrid 合成踢鼓＋取樣、electronic 合成鼓＋取樣拍手 */
  kit?: 'acoustic' | 'hybrid' | 'electronic';
  /** 第二個和聲軌的音程（音階級數，預設 -2） */
  harmonyStep?: number;
  harmony?: boolean;
  arp?: { kind: ArpKind; rate: 1 | 2; range: [number, number]; vel: number };
  pad?: boolean;
  /** 能量 0–1：影響力度與音符密度 */
  energy: number;
  /** 各聲部的 GM 音色 */
  prog: Partial<Record<TrackRole, number>>;
  /** 建議的聲音方案 */
  scheme: SchemeId;
  /** 開頭重音鈸 */
  crash?: boolean;
}

